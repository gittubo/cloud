// Fills in a simple purchase agreement from the agreed deal. A starting point only:
// have a local investor-friendly attorney or title company approve your template.
import type { Lead, Settings } from './types.ts';

const esc = (s: unknown) => String(s ?? '').replace(/[&<>"]/g, (c) => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;' }[c]!));

export function purchaseAgreementHtml(lead: Lead, price: number, s: Settings, today = new Date()): string {
  const closing = new Date(today);
  closing.setDate(closing.getDate() + s.closeDays);
  const date = (d: Date) => d.toISOString().slice(0, 10);
  return `<!doctype html><html><head><meta charset="utf-8"><title>Purchase Agreement: ${esc(lead.address)}</title>
<style>body{font:15px/1.6 Georgia,serif;max-width:720px;margin:40px auto;padding:0 16px;color:#111}h1{font-size:22px}.sig{margin-top:48px;display:grid;grid-template-columns:1fr 1fr;gap:32px}.line{border-top:1px solid #111;padding-top:4px}.note{background:#fff7d6;padding:8px 12px;border-radius:6px;font:13px system-ui}</style></head><body>
<p class="note">DRAFT generated by AI Dream Team. Have a licensed attorney or title company in ${esc(lead.state)} review your template before use.</p>
<h1>Residential Purchase and Sale Agreement</h1>
<p>Date: ${date(today)}</p>
<p><b>Seller:</b> ${esc(lead.ownerName ?? '________________')}<br><b>Buyer:</b> ${esc(s.companyName)} and/or assigns</p>
<p><b>Property:</b> ${esc(lead.address)}, ${esc(lead.city)}, ${esc(lead.state)} ${esc(lead.zip)}</p>
<ol>
<li><b>Purchase price:</b> $${price.toLocaleString()}, paid in cash at closing.</li>
<li><b>Earnest money:</b> $________ deposited with the closing agent within 3 business days of acceptance.</li>
<li><b>Condition:</b> Property sold AS-IS. Seller makes no repairs.</li>
<li><b>Inspection period:</b> Buyer may inspect the property within 10 days of acceptance and may cancel in writing during that period, with earnest money returned.</li>
<li><b>Closing:</b> On or before ${date(closing)} at a title company or closing attorney chosen by Buyer. Buyer pays customary closing costs. Seller pays off existing liens from proceeds.</li>
<li><b>Assignment:</b> Buyer may assign this agreement. Seller's price and terms do not change on assignment.</li>
<li><b>Title:</b> Seller conveys marketable title by general warranty deed (or executor's/administrator's deed for an estate).</li>
<li><b>Possession:</b> At closing unless otherwise agreed in writing: ______________________.</li>
</ol>
<div class="sig"><div><div class="line">Seller signature / date</div></div><div><div class="line">Buyer: ${esc(s.yourName)}, for ${esc(s.companyName)}</div></div></div>
</body></html>`;
}
